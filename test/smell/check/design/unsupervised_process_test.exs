defmodule Smell.Check.Design.UnsupervisedProcessTest do
  use Credo.Test.Case

  @described_check Smell.Check.Design.UnsupervisedProcess

  defp run(source, filename \\ "lib/server.ex", params \\ []) do
    source
    |> to_source_file(filename)
    |> run_check(@described_check, params)
  end

  defp in_callback(body, head \\ "handle_info(message, state)") do
    """
    defmodule Server do
      def #{head} do
        #{body}
        {:noreply, state}
      end
    end
    """
  end

  describe "reports" do
    test "a server that starts one process per message" do
      """
      defmodule Acceptor do
        use GenServer

        def handle_info(:accept, listen_socket) do
          {:ok, socket} = :gen_tcp.accept(listen_socket)
          {:ok, pid} = Connection.start_link(socket)
          :ok = :gen_tcp.controlling_process(socket, pid)
          send(self(), :accept)
          {:noreply, listen_socket}
        end
      end
      """
      |> run()
      |> assert_issue(fn issue ->
        assert issue.trigger == "Connection.start_link"
        assert issue.line_no == 6
        assert issue.column == 18

        assert issue.message ==
                 "`Connection.start_link` starts a process in `handle_info/2`, " <>
                   "outside a supervision tree. Start it under a supervisor, " <>
                   "for example with `DynamicSupervisor.start_child/2`."
      end)
    end

    test "every function that starts a long-running process" do
      for start <- [
            "GenServer.start(Worker, [])",
            "GenServer.start_link(Worker, [], name: name)",
            "Agent.start(fn -> %{} end)",
            "Agent.start_link(fn -> %{} end)",
            "Supervisor.start_link(children, strategy: :one_for_one)",
            "DynamicSupervisor.start_link(strategy: :one_for_one)",
            "PartitionSupervisor.start_link(child_spec: Worker, name: name)",
            "Registry.start_link(keys: :unique, name: name)",
            "Task.Supervisor.start_link()",
            ":gen_server.start_link(Worker, [], [])",
            ":gen_statem.start(Worker, [], [])",
            ":gen_event.start_link()",
            ":supervisor.start_link(Worker, [])",
            "MyApp.Worker.start_link(message)",
            "__MODULE__.start_link(message)",
            "__MODULE__.Worker.start_link(message)"
          ] do
        start
        |> in_callback()
        |> run()
        |> assert_issue(fn issue ->
          assert issue.line_no == 3
          assert issue.column == 5, "#{start}: column #{issue.column}"
        end)
      end
    end

    test "every callback that runs once per message" do
      for head <- [
            "handle_call(request, from, state)",
            "handle_cast(request, state)",
            "handle_info(message, state)",
            "handle_event(event, params, socket)",
            "handle_event(type, content, state, data)",
            "handle_in(event, payload, socket)",
            "handle_info(message, state) when is_tuple(message)"
          ] do
        "Worker.start_link(state)"
        |> in_callback(head)
        |> run()
        |> assert_issue(fn issue ->
          name = head |> String.split("(") |> hd()
          assert issue.message =~ "in `#{name}/"
        end)
      end
    end

    test "starts inside pipes, captures, anonymous functions and with" do
      """
      defmodule Server do
        def handle_cast({:open, sockets}, state) do
          first = sockets |> hd() |> Connection.start_link()
          pids = Enum.map(sockets, &Connection.start_link/1)
          Enum.each(sockets, fn socket -> Connection.start_link(socket) end)

          with {:ok, pid} <- Agent.start_link(fn -> state end) do
            {:noreply, {first, pids, pid}}
          end
        end
      end
      """
      |> run()
      |> assert_issues(fn issues ->
        assert issues |> Enum.map(& &1.line_no) |> Enum.sort() == [3, 4, 5, 7]
      end)
    end

    test "callbacks in the keyword syntax and generated by a quote" do
      """
      defmodule Server do
        def handle_info(:start, state), do: {:noreply, Worker.start_link(state)}

        defmacro __using__(_opts) do
          quote do
            def handle_call(:start, _from, state) do
              {:reply, Worker.start_link(state), state}
            end
          end
        end
      end
      """
      |> run()
      |> assert_issues(fn issues -> assert length(issues) == 2 end)
    end

    test "test files when :exclude_test_files is false" do
      "Worker.start_link(state)"
      |> in_callback()
      |> run("test/support/server.ex", exclude_test_files: false)
      |> assert_issue()
    end
  end

  describe "does not report" do
    test "starts in functions that start one process per server" do
      """
      defmodule Server do
        use GenServer

        def start_link(opts), do: GenServer.start_link(__MODULE__, opts, name: __MODULE__)
        def start(opts), do: GenServer.start(__MODULE__, opts)

        def child_spec(opts) do
          %{id: __MODULE__, start: {__MODULE__, :start_link, [opts]}}
        end

        def init(opts) do
          {:ok, sup} = DynamicSupervisor.start_link(strategy: :one_for_one)
          {:ok, %{sup: sup, opts: opts}, {:continue, :load}}
        end

        def handle_continue(:load, state) do
          {:ok, cache} = Agent.start_link(fn -> %{} end)
          {:noreply, Map.put(state, :cache, cache)}
        end
      end

      defmodule MyApp.Application do
        use Application

        def start(_type, _args) do
          Supervisor.start_link([Server], strategy: :one_for_one)
        end
      end
      """
      |> run()
      |> refute_issues()
    end

    test "tasks and spawned processes" do
      for start <- [
            "Task.start(fn -> reply(state) end)",
            "Task.start_link(fn -> reply(state) end)",
            "Task.async(fn -> reply(state) end)",
            "spawn(fn -> reply(state) end)",
            "spawn_link(fn -> reply(state) end)",
            "Process.spawn(fn -> reply(state) end, [])",
            ":erlang.spawn(fn -> reply(state) end)",
            ":proc_lib.spawn_link(fn -> reply(state) end)"
          ] do
        start
        |> in_callback()
        |> run()
        |> refute_issues()
      end
    end

    test "processes started under a supervisor" do
      for start <- [
            "DynamicSupervisor.start_child(MyApp.Sup, {Worker, state})",
            "Supervisor.start_child(MyApp.Sup, %{id: 1, start: {Worker, :start_link, [state]}})",
            "Task.Supervisor.start_child(MyApp.TaskSup, fn -> reply(state) end)"
          ] do
        start
        |> in_callback()
        |> run()
        |> refute_issues()
      end
    end

    test "functions that are not per-message callbacks" do
      """
      defmodule Server do
        def run(state), do: Worker.start_link(state)
        defp handle_info(message, state), do: Worker.start_link({message, state})
        def handle_info(message), do: Worker.start_link(message)
        def handle_call(request, state), do: Worker.start_link({request, state})
        def handle_continue(:open, state), do: Worker.start_link(state)
      end
      """
      |> run()
      |> refute_issues()
    end

    test "other calls named start or start_link" do
      for call <- [
            "Application.start(:my_app)",
            "Proxy.start()",
            "Worker.start_child(state)",
            "start_link(state)",
            "module.start_link(state)",
            ":application.start(:my_app)",
            ":gen_server.call(Worker, :start_link)",
            "Task.Supervisor.async_nolink(MyApp.TaskSup, fn -> state end)"
          ] do
        call
        |> in_callback()
        |> run()
        |> refute_issues()
      end
    end

    test "test files" do
      "Worker.start_link(state)"
      |> in_callback()
      |> run("test/support/server.ex")
      |> refute_issues()
    end
  end
end
